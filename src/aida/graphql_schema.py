@strawberry.type(description="Metadata reads. Nothing here executes against a source.")
class Query:
    @field_resolver("One datasource by id, as `GET /v1/datasources/{id}`.")
    async def datasource(self, info: Info, id: strawberry.ID) -> DataSource | None:
        return DataSource.of(await get_datasource(info.context, _uuid(id)))

    @field_resolver(
        "The caller's organization's datasources, as `GET /v1/organizations/{id}/datasources`."
    )
    async def datasources(
        self,
        info: Info,
        first: int = _DEFAULT_PAGE,
        after: str | None = None,
        q: str | None = None,
        status: str | None = None,
    ) -> DataSourceConnection | None:
        page = await list_datasources(info.context, first=first, after=after, q=q, status=status)
        return DataSourceConnection.of(page)

    @field_resolver(
        "Execution receipts (R11-GQL02), newest first: the caller's own, or every caller's in "
        "the organization for PlatformAdmin and Auditor, optionally of one status. A stale "
        "PENDING receipt is settled from its recorded execution as it is read, so asking for "
        "PENDING lists what is still genuinely unknown. Never rows."
    )
    async def governed_executions(
        self,
        info: Info,
        status: str | None = None,
        first: int = _DEFAULT_PAGE,
        after: str | None = None,
    ) -> GovernedExecutionReceiptConnection | None:
        scope = info.context
        if first < 1 or first > scope.limits.max_page_size:
            raise ReadRefused("INVALID_ARGUMENT", "PAGE_SIZE_OUT_OF_RANGE")
        async with scope.lock:
            try:
                page = await list_receipts(
                    scope.session,
                    scope.context,
                    scope.settings,
                    organization_id=scope.organization_id,
                    status=status,
                    first=first,
                    after=after,
                )
            except ExecutionRefused as refused:
                raise ReadRefused(refused.code, refused.reason) from refused
        return GovernedExecutionReceiptConnection(
            nodes=[GovernedExecutionReceipt.of(record) for record in page.items],
            page_info=PageInfo(has_next_page=page.has_next_page, end_cursor=page.end_cursor),
            total_count=page.total,
        )

    @field_resolver(
        "One governed execution receipt (R11-GQL02): the caller's own, or any in the "
        "organization for PlatformAdmin and Auditor. Never rows."
    )
    async def governed_execution(
        self, info: Info, id: strawberry.ID
    ) -> GovernedExecutionReceipt | None:
        scope = info.context
        async with scope.lock:
            try:
                record = await load_receipt(
                    scope.session,
                    scope.context,
                    scope.settings,
                    organization_id=scope.organization_id,
                    record_id=_uuid(id),
                )
            except ExecutionRefused as refused:
                raise ReadRefused(refused.code, refused.reason) from refused
        return GovernedExecutionReceipt.of(record)

    @field_resolver("One table by id, decided as its columns route decides it.")
    async def table(self, info: Info, id: strawberry.ID) -> Table | None:
        return Table.of_row(await get_table(info.context, _uuid(id)))

    @field_resolver(
        "Tables the caller may read. With `datasourceId`, as "
        "`GET /v1/datasources/{id}/tables`; without it, across the caller's organization, "
        "with unreadable datasources removed before counting and paging."
    )
    async def tables(
        self,
        info: Info,
        datasource_id: strawberry.ID | None = None,
        first: int = _DEFAULT_PAGE,
        after: str | None = None,
        q: str | None = None,
        object_type: str | None = None,
        status: str = "ACTIVE",
    ) -> TableConnection | None:
        if datasource_id is not None:
            page = await list_datasource_tables(
                info.context,
                _uuid(datasource_id),
                first=first,
                after=after,
                q=q,
                object_type=object_type,
                status=status,
            )
        else:
            page = await list_organization_tables(
                info.context, first=first, after=after, q=q, object_type=object_type, status=status
            )
        return TableConnection.of(page)


