_Resolver = Callable[..., Coroutine[Any, Any, Any]]


def field_resolver(description: str) -> Callable[[_Resolver], StrawberryField]:
    """`@strawberry.field(description=...)`, with a type strict mypy can see.

    Strawberry types its keyword-only `field(...)` overload as returning `Any` (it
    doubles as a plain field default), which makes every decorated resolver
    "untyped" under `mypy --strict`. Passing the resolver positionally selects
    the overload that returns a `StrawberryField` -- the same object the
    decorator form builds. `scripts/generate_surface_control_matrix.py` finds
    resolvers by this decorator's name.
    """

    def decorate(resolver: _Resolver) -> StrawberryField:
        return strawberry.field(resolver, description=description)

    return decorate


def _id(value: UUID) -> strawberry.ID:
    return strawberry.ID(str(value))


def _uuid(value: strawberry.ID) -> UUID:
    try:
        return UUID(str(value))
    except ValueError as exc:
        raise ReadRefused("INVALID_ARGUMENT", "INVALID_ID") from exc


@strawberry.type(description="Where a page ends and whether another follows it.")
class PageInfo:
    has_next_page: bool
    end_cursor: str | None = strawberry.field(
        description="Pass as `after` for the next page. The same opaque keyset cursor "
        "the equivalent REST route returns as `next_cursor`."
    )


def _page_info(page: Page[Any]) -> PageInfo:
    return PageInfo(has_next_page=page.has_next_page, end_cursor=page.end_cursor)


@strawberry.type(
    description="A registered source system, as `GET /v1/datasources/{id}` returns it."
)
class DataSource:
    id: strawberry.ID
    organization_id: strawberry.ID
    project_id: strawberry.ID
    line_of_business_id: strawberry.ID
    data_domain_id: strawberry.ID
    name: str
    connector_type: str
    dialect: str
    environment: str
    network_zone: str
    status: str
    max_concurrency: int
    created_at: datetime
    updated_at: datetime
    read: strawberry.Private[DataSourceSummaryRead]

    @classmethod
    def of(cls, read: DataSourceSummaryRead) -> DataSource:
        return cls(
            id=_id(read.id),
            organization_id=_id(read.organization_id),
            project_id=_id(read.project_id),
            line_of_business_id=_id(read.line_of_business_id),
            data_domain_id=_id(read.data_domain_id),
            name=read.name,
            connector_type=read.connector_type,
            dialect=read.dialect,
            environment=read.environment,
            network_zone=read.network_zone,
            status=read.status,
            max_concurrency=read.max_concurrency,
            created_at=read.created_at,
            updated_at=read.updated_at,
            read=read,
        )

    @field_resolver("This datasource's tables, as `GET /v1/datasources/{id}/tables`.")
    async def tables(
        self,
        info: Info,
        first: int = _DEFAULT_PAGE,
        after: str | None = None,
        q: str | None = None,
        object_type: str | None = None,
        status: str = "ACTIVE",
    ) -> TableConnection | None:
        page = await list_tables(
            info.context,
            self.read,
            first=first,
            after=after,
            q=q,
            object_type=object_type,
            status=status,
        )
        return TableConnection.of(page)


@strawberry.type(description="A table, view or other relation, as the catalog records it.")
class Table:
    id: strawberry.ID
    datasource_id: strawberry.ID
    schema_id: strawberry.ID
    name: str
    object_type: str
    status: str
    fingerprint: str
    row: strawberry.Private[MetadataTable | None]

    @classmethod
    def of(cls, read: MetadataTableRead, row: MetadataTable | None = None) -> Table:
        return cls(
            id=_id(read.id),
            datasource_id=_id(read.datasource_id),
            schema_id=_id(read.schema_id),
            name=read.name,
            object_type=read.object_type,
            status=read.status,
            fingerprint=read.fingerprint,
            row=row,
        )

    @classmethod
    def of_row(cls, row: MetadataTable) -> Table:
        return cls.of(MetadataTableRead.model_validate(row), row)

    def _subject(self) -> MetadataTable | UUID:
        """What a child read is about. A table reached through a list carries only its
        id; the read service loads it with its siblings and decides it on its own --
        the same table-level decision `GET /v1/tables/{id}/columns` makes."""
        return self.row if self.row is not None else _uuid(self.id)

    @field_resolver("The datasource this table belongs to.")
    async def datasource(self, info: Info) -> DataSource | None:
        return DataSource.of(await get_datasource(info.context, _uuid(self.datasource_id)))

    @field_resolver("Active columns in ordinal order, as `GET /v1/tables/{id}/columns`.")
    async def columns(
        self, info: Info, first: int = _DEFAULT_PAGE, after: str | None = None
    ) -> ColumnConnection | None:
        table, page = await list_columns(info.context, self._subject(), first=first, after=after)
        return ColumnConnection.of(page, table)

    @field_resolver(
        "Keys and references, as `GET /v1/tables/{id}/constraints`. A referenced "
        "table is authorized on its own."
    )
    async def constraints(
        self, info: Info, first: int = _DEFAULT_PAGE, after: str | None = None
    ) -> ConstraintConnection | None:
        page = await list_constraints(info.context, self._subject(), first=first, after=after)
        return ConstraintConnection.of(page)

    @field_resolver("The approved description, as `GET /v1/tables/{id}/description`.")
    async def description(self, info: Info) -> ApprovedTableDescription | None:
        found = await table_description(info.context, self._subject())
        return ApprovedTableDescription.of(found)


